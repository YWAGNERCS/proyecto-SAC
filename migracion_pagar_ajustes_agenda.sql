-- ============================================================
-- Migración: cuentas por pagar, ajustes de inventario, costo en cada venta y agenda (31/10/2026)
--
--  1) COMPRAS: forma de pago al proveedor.
--       tipo_pago        CONTADO | CREDITO   (las compras anteriores quedan CONTADO)
--       dias_credito, fecha_vencimiento       (solo CREDITO)
--       estado_pago      PAGADA | PENDIENTE  (las anteriores quedan PAGADA)
--     PAGOS_PROVEEDOR: abonos a una compra a crédito; se anulan con motivo, no se borran.
--  2) AJUSTES_INVENTARIO: entradas y salidas de stock que no son compra, venta ni orden
--     (conteo físico, merma, dañado, robo, stock inicial...). Salen en el kardex.
--  3) DETALLE_VENTA.costo_unitario: costo del producto al momento de vender, en la moneda
--     de la venta, para el reporte de rentabilidad. En las ventas anteriores se completa con
--     el costo ACTUAL del producto (aproximación: no se guardó el de entonces).
--  4) ORDENES_TRABAJO: hora de inicio (HH:mm) y duración, para la agenda de técnicos.
--
-- Ejecutar UNA vez, con el backend detenido:
--   Get-Content migracion_pagar_ajustes_agenda.sql | docker exec -i SGE-JD sqlplus -s jdrefrigeracion/<password>@FREEPDB1
-- Se puede ejecutar varias veces: lo que ya existe no se toca.
-- ============================================================
SET FEEDBACK ON
SET SERVEROUTPUT ON

DECLARE
    v_existe NUMBER;

    PROCEDURE agregar(p_tabla VARCHAR2, p_columna VARCHAR2, p_definicion VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO v_existe
          FROM all_tab_columns
         WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
           AND table_name = p_tabla AND column_name = UPPER(p_columna);
        IF v_existe = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_tabla || ' ADD (' || p_columna || ' ' || p_definicion || ')';
            DBMS_OUTPUT.PUT_LINE(p_tabla || '.' || p_columna || ': agregada');
        ELSE
            DBMS_OUTPUT.PUT_LINE(p_tabla || '.' || p_columna || ': ya existía');
        END IF;
    END;
BEGIN
    agregar('COMPRAS', 'tipo_pago', 'VARCHAR2(10) DEFAULT ''CONTADO'' NOT NULL');
    agregar('COMPRAS', 'dias_credito', 'NUMBER(3)');
    agregar('COMPRAS', 'fecha_vencimiento', 'DATE');
    agregar('COMPRAS', 'estado_pago', 'VARCHAR2(10) DEFAULT ''PAGADA'' NOT NULL');
    agregar('COMPRAS', 'registrado_por', 'VARCHAR2(100)');
    agregar('DETALLE_VENTA', 'costo_unitario', 'NUMBER(12,2)');
    agregar('ORDENES_TRABAJO', 'hora_inicio', 'VARCHAR2(5)');
    agregar('ORDENES_TRABAJO', 'duracion_minutos', 'NUMBER(4)');
END;
/

CREATE TABLE IF NOT EXISTS pagos_proveedor (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id         NUMBER        NOT NULL REFERENCES compras (id),
    fecha_pago        DATE          NOT NULL,
    monto             NUMBER(12,2)  NOT NULL,
    metodo            VARCHAR2(20)  NOT NULL,
    numero_operacion  VARCHAR2(50),
    observacion       VARCHAR2(300),
    estado            VARCHAR2(10)  DEFAULT 'VIGENTE' NOT NULL,
    fecha_anulacion   DATE,
    motivo_anulacion  VARCHAR2(300),
    anulado_por       VARCHAR2(100),
    registrado_por    VARCHAR2(100),
    fecha_registro    TIMESTAMP     NOT NULL,
    CONSTRAINT ck_pago_prov_monto CHECK (monto > 0),
    CONSTRAINT ck_pago_prov_estado CHECK (estado IN ('VIGENTE', 'ANULADO')),
    CONSTRAINT ck_pago_prov_anulado CHECK (estado = 'VIGENTE' OR (fecha_anulacion IS NOT NULL AND motivo_anulacion IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ix_pago_prov_compra ON pagos_proveedor (compra_id);

CREATE TABLE IF NOT EXISTS ajustes_inventario (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id      NUMBER        NOT NULL REFERENCES productos (id),
    fecha            DATE          NOT NULL,
    tipo             VARCHAR2(10)  NOT NULL,
    cantidad         NUMBER(9)     NOT NULL,
    motivo           VARCHAR2(20)  NOT NULL,
    observacion      VARCHAR2(300),
    stock_anterior   NUMBER(9)     NOT NULL,
    stock_nuevo      NUMBER(9)     NOT NULL,
    registrado_por   VARCHAR2(100),
    fecha_registro   TIMESTAMP     NOT NULL,
    CONSTRAINT ck_ajuste_tipo CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT ck_ajuste_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_ajuste_stock CHECK (stock_nuevo >= 0)
);
CREATE INDEX IF NOT EXISTS ix_ajuste_producto ON ajustes_inventario (producto_id, fecha);

-- Costo de las ventas anteriores: costo actual del producto llevado a la moneda de la venta
UPDATE detalle_venta d
   SET costo_unitario = (
       SELECT CASE
                WHEN p.moneda = v.moneda THEN p.costo_base
                WHEN p.moneda = 'DOLARES' AND v.moneda = 'SOLES' AND v.tipo_cambio IS NOT NULL
                     THEN ROUND(p.costo_base * v.tipo_cambio, 2)
                WHEN p.moneda = 'SOLES' AND v.moneda = 'DOLARES' AND v.tipo_cambio IS NOT NULL
                     THEN ROUND(p.costo_base / v.tipo_cambio, 2)
              END
         FROM productos p JOIN ventas v ON v.id = d.venta_id
        WHERE p.id = d.producto_id)
 WHERE d.costo_unitario IS NULL;

COMMIT;
EXIT
