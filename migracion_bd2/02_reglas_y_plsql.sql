-- ============================================================
-- Migración BD2 · 2/7 · Reglas en la base y motor PL/SQL (BD2 S1 y S3)
--  * CHECK que antes solo cuidaba Java: cantidad > 0, precio y costo no negativos, descuento 0-100, stock >= 0.
--  * LOG_ERRORES y SP_REGISTRAR_ERROR (transacción autónoma: el error queda aunque la operación se revierta).
--  * FN_SUBTOTAL_LINEA, FN_TOTAL_VENTA y SP_REGISTRAR_VENTA en su versión 2 (S3): espera máxima de 10 s,
--    cada error registrado antes de relanzarse.
-- El backend NO usa SP_REGISTRAR_VENTA: es otra puerta de entrada (por ejemplo, una carga desde SQL). Una venta
-- que entra por ahí queda sin comprobante y el backend se lo emite en su siguiente ronda (hasta 3 min, BD2 S4),
-- igual que a una venta propia cuyo envío falló. Se deja así a propósito.
-- Lo ejecuta migracion_bd2\migrar.ps1 como SYSDBA. Se puede repetir.
-- ============================================================
whenever sqlerror exit failure
set serveroutput on feedback off
ALTER SESSION SET CONTAINER = FREEPDB1;
-- otra vez: DBMS_OUTPUT se habilita por contenedor
set serveroutput on
ALTER SESSION SET CURRENT_SCHEMA = JDREFRIGERACION;
DECLARE
    PROCEDURE ejecutar(p_sql VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
        DBMS_OUTPUT.PUT_LINE('  ok: ' || SUBSTR(p_sql, 1, 110));
    EXCEPTION WHEN OTHERS THEN
        -- ya existe: nombre de restricción usado (-2264) o de objeto usado (-955)
        IF SQLCODE IN (-2264, -955) THEN
            DBMS_OUTPUT.PUT_LINE('  ya existe: ' || SUBSTR(p_sql, 1, 100));
        ELSE
            RAISE;
        END IF;
    END;
BEGIN
    ejecutar('ALTER TABLE detalle_venta ADD CONSTRAINT ck_detalle_venta_cantidad CHECK (cantidad > 0)');
    ejecutar('ALTER TABLE detalle_venta ADD CONSTRAINT ck_detalle_venta_precio CHECK (precio_unitario >= 0)');
    ejecutar('ALTER TABLE detalle_venta ADD CONSTRAINT ck_detalle_venta_descuento CHECK (descuento_porcentaje BETWEEN 0 AND 100)');
    ejecutar('ALTER TABLE productos ADD CONSTRAINT ck_producto_stock CHECK (stock_actual >= 0)');
    ejecutar('ALTER TABLE productos ADD CONSTRAINT ck_producto_costo_margen CHECK (costo_base >= 0 AND margen_porcentaje >= 0)');
    ejecutar('CREATE TABLE log_errores (
        id_log          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        objeto          VARCHAR2(60)   NOT NULL,
        codigo_error    NUMBER         NOT NULL,
        mensaje_error   VARCHAR2(500),
        contexto        VARCHAR2(500),
        traza           VARCHAR2(1000),
        fecha_evento    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
        usuario_oracle  VARCHAR2(128)  DEFAULT USER NOT NULL,
        programa        VARCHAR2(64))');
    ejecutar('CREATE INDEX ix_log_errores_fecha ON log_errores (fecha_evento)');
END;
/

CREATE OR REPLACE PROCEDURE sp_registrar_error(
    p_objeto   IN VARCHAR2,
    p_codigo   IN NUMBER,
    p_mensaje  IN VARCHAR2,
    p_contexto IN VARCHAR2 DEFAULT NULL
) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO log_errores (objeto, codigo_error, mensaje_error, contexto, traza, programa)
    VALUES (SUBSTR(p_objeto, 1, 60), p_codigo, SUBSTR(p_mensaje, 1, 500), SUBSTR(p_contexto, 1, 500),
            SUBSTR(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE, 1, 1000),
            SUBSTR(SYS_CONTEXT('USERENV', 'MODULE'), 1, 64));
    COMMIT;
END sp_registrar_error;
/

CREATE OR REPLACE FUNCTION fn_subtotal_linea(
    p_cantidad  IN NUMBER,
    p_precio    IN NUMBER,
    p_descuento IN NUMBER DEFAULT 0
) RETURN NUMBER IS
BEGIN
    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'La cantidad debe ser mayor que cero.');
    END IF;
    IF p_precio IS NULL OR p_precio < 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'El precio no puede ser negativo.');
    END IF;
    IF NVL(p_descuento, 0) NOT BETWEEN 0 AND 100 THEN
        RAISE_APPLICATION_ERROR(-20003, 'El descuento debe estar entre 0 y 100 %.');
    END IF;
    RETURN ROUND(p_precio * p_cantidad * (1 - NVL(p_descuento, 0) / 100), 2);
END fn_subtotal_linea;
/

CREATE OR REPLACE FUNCTION fn_total_venta(p_venta_id IN NUMBER) RETURN NUMBER IS
    v_subtotal NUMBER;
    v_lineas   NUMBER;
BEGIN
    SELECT COUNT(*), ROUND(NVL(SUM(fn_subtotal_linea(cantidad, precio_unitario, descuento_porcentaje)), 0), 2)
    INTO v_lineas, v_subtotal
    FROM detalle_venta
    WHERE venta_id = p_venta_id;

    IF v_lineas = 0 THEN
        sp_registrar_error('FN_TOTAL_VENTA', -20004, 'Venta sin líneas o inexistente', 'venta=' || p_venta_id);
        RAISE_APPLICATION_ERROR(-20004, 'La venta ' || p_venta_id || ' no existe o no tiene líneas.');
    END IF;
    RETURN v_subtotal + ROUND(v_subtotal * 0.18, 2);
END fn_total_venta;
/

CREATE OR REPLACE PROCEDURE sp_registrar_venta(
    p_cliente_id  IN  NUMBER,
    p_producto_id IN  NUMBER,
    p_cantidad    IN  NUMBER,
    p_descuento   IN  NUMBER,
    p_rol         IN  VARCHAR2,
    p_vendedor    IN  VARCHAR2,
    p_venta_id    OUT NUMBER,
    p_total       OUT NUMBER
) IS
    c_objeto   CONSTANT VARCHAR2(30) := 'SP_REGISTRAR_VENTA';
    -- Fila bloqueada por otra transacción: Oracle 23 da ORA-00054 al vencer el WAIT; 19c daba ORA-30006
    e_fila_ocupada     EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_fila_ocupada, -54);
    e_fila_ocupada_19c EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_fila_ocupada_19c, -30006);
    e_valor_largo      EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_valor_largo, -12899);

    v_contexto VARCHAR2(500) := 'cliente=' || p_cliente_id || ' producto=' || p_producto_id
                                || ' cantidad=' || p_cantidad || ' descuento=' || p_descuento || ' rol=' || p_rol;
    v_cliente  clientes.id%TYPE;
    v_sector   productos.sector%TYPE;
    v_moneda   productos.moneda%TYPE;
    v_stock    productos.stock_actual%TYPE;
    v_precio   NUMBER(12,2);
    v_costo    NUMBER(12,2);
    v_tope     NUMBER(5,2);
    v_subtotal NUMBER(12,2);

    PROCEDURE fallar(p_codigo NUMBER, p_mensaje VARCHAR2) IS
    BEGIN
        sp_registrar_error(c_objeto, p_codigo, p_mensaje, v_contexto);
        RAISE_APPLICATION_ERROR(p_codigo, p_mensaje);
    END fallar;
BEGIN
    BEGIN
        SELECT id INTO v_cliente FROM clientes WHERE id = p_cliente_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            sp_registrar_error(c_objeto, SQLCODE, 'Cliente no encontrado: ' || p_cliente_id, v_contexto);
            RAISE_APPLICATION_ERROR(-20010, 'El cliente ' || p_cliente_id || ' no existe.');
    END;

    BEGIN
        SELECT sector, moneda, NVL(stock_actual, 0),
               ROUND(costo_base * (1 + margen_porcentaje / 100), 2),
               NVL(ultimo_costo_compra, costo_base)
        INTO v_sector, v_moneda, v_stock, v_precio, v_costo
        FROM productos
        WHERE id = p_producto_id
        FOR UPDATE WAIT 10;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            sp_registrar_error(c_objeto, SQLCODE, 'Producto no encontrado: ' || p_producto_id, v_contexto);
            RAISE_APPLICATION_ERROR(-20015, 'El producto ' || p_producto_id || ' no existe.');
        WHEN e_fila_ocupada OR e_fila_ocupada_19c THEN
            sp_registrar_error(c_objeto, SQLCODE, SQLERRM, v_contexto);
            RAISE_APPLICATION_ERROR(-20017, 'El producto ' || p_producto_id
                || ' está siendo usado por otra venta o compra. Intente de nuevo en unos segundos.');
    END;

    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        fallar(-20016, 'La cantidad debe ser mayor que cero.');
    END IF;
    IF v_moneda <> 'SOLES' THEN
        fallar(-20011, 'Solo se registran productos en soles (los de dólares necesitan tipo de cambio).');
    END IF;

    BEGIN
        SELECT CASE WHEN UPPER(p_rol) = 'ADMIN' THEN tope_admin ELSE tope_asistente END
        INTO v_tope FROM topes_descuento WHERE id = 1;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_tope := CASE WHEN UPPER(p_rol) = 'ADMIN' THEN 30 ELSE 10 END;
    END;
    IF NVL(p_descuento, 0) > v_tope THEN
        fallar(-20012, 'El descuento de ' || p_descuento || ' % supera el tope de ' || v_tope || ' %.');
    END IF;
    IF v_sector = 'MATERIAL_SERVICIO' AND v_stock < p_cantidad THEN
        fallar(-20013, 'Stock insuficiente: hay ' || v_stock || ' y se piden ' || p_cantidad || '.');
    END IF;

    v_subtotal := fn_subtotal_linea(p_cantidad, v_precio, p_descuento);
    p_total := v_subtotal + ROUND(v_subtotal * 0.18, 2);
    IF p_total > 700 THEN
        fallar(-20014, 'Total de ' || p_total || ' soles: supera 700 y necesita detracción o retención (usar el sistema).');
    END IF;

    INSERT INTO ventas (cliente_id, fecha_venta, moneda, tipo_pago, estado_pago, estado, tipo_deduccion,
                        vendedor_nombre)
    VALUES (v_cliente, TRUNC(SYSDATE), 'SOLES', 'CONTADO', 'PAGADO', 'REGISTRADA', 'NINGUNA', p_vendedor)
    RETURNING id INTO p_venta_id;

    INSERT INTO detalle_venta (venta_id, producto_id, cantidad, precio_unitario, descuento_porcentaje,
                               costo_unitario, precio_catalogo)
    VALUES (p_venta_id, p_producto_id, p_cantidad, v_precio, NVL(p_descuento, 0), v_costo, v_precio);

    IF v_sector = 'MATERIAL_SERVICIO' THEN
        UPDATE productos SET stock_actual = stock_actual - p_cantidad WHERE id = p_producto_id;
    END IF;
EXCEPTION
    WHEN e_valor_largo THEN
        sp_registrar_error(c_objeto, SQLCODE, SQLERRM, v_contexto);
        RAISE_APPLICATION_ERROR(-20018, 'Un dato es demasiado largo (el nombre del vendedor admite 60 caracteres).');
    WHEN OTHERS THEN
        IF SQLCODE NOT BETWEEN -20999 AND -20000 THEN
            sp_registrar_error(c_objeto, SQLCODE, SQLERRM, v_contexto);
        END IF;
        RAISE;
END sp_registrar_venta;
/
set feedback on
column object_name format a24
SELECT object_name, object_type, status FROM dba_objects
WHERE owner = 'JDREFRIGERACION' AND object_name IN ('SP_REGISTRAR_VENTA', 'FN_TOTAL_VENTA', 'SP_REGISTRAR_ERROR', 'FN_SUBTOTAL_LINEA', 'LOG_ERRORES')
ORDER BY object_name;
exit
