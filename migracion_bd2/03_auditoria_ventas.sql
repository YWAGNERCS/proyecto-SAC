-- ============================================================
-- Migración BD2 · 3/7 · Auditoría de ventas y regla de anulación (BD2 S2, S5 y S11)
--  * VENTA_AUDITORIA: una fila por cada INSERT, UPDATE o DELETE de una venta. Sin FK (el registro de un DELETE
--    sobrevive a la venta). Particionada por mes con INTERVAL (S11): la purga por antigüedad es un
--    DROP PARTITION ... UPDATE GLOBAL INDEXES, no un DELETE (S11: 240 ms frente a 1 170 ms, sin dejar la PK UNUSABLE).
--  * TRG_VENTA_ESTADO_BU: una venta ANULADA no vuelve atrás; anular exige motivo (5+) y quién.
--  * TRG_VENTA_AUDITORIA: escribe la auditoría, con el MODULE de la sesión (el backend lo fija, S14).
--  * IX_VENTA_AUDITORIA_ACCION: B-Tree LOCAL. El Bitmap de S5 bloqueó 11,4 s una venta simultánea.
-- Lo ejecuta migracion_bd2\migrar.ps1 como SYSDBA. Se puede repetir.
-- ============================================================
whenever sqlerror exit failure
set serveroutput on feedback off
ALTER SESSION SET CONTAINER = FREEPDB1;
-- otra vez: DBMS_OUTPUT se habilita por contenedor
set serveroutput on
ALTER SESSION SET CURRENT_SCHEMA = JDREFRIGERACION;
DECLARE
    PROCEDURE ejecutar(p_sql VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
        DBMS_OUTPUT.PUT_LINE('  ok: ' || SUBSTR(p_sql, 1, 110));
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE IN (-955, -1408) THEN   -- ya existe / ya hay un índice con esas columnas
            DBMS_OUTPUT.PUT_LINE('  ya existe: ' || SUBSTR(p_sql, 1, 100));
        ELSE
            RAISE;
        END IF;
    END;
BEGIN
    ejecutar('CREATE TABLE venta_auditoria (
        id_auditoria          NUMBER GENERATED BY DEFAULT AS IDENTITY,
        id_venta              NUMBER        NOT NULL,
        accion                VARCHAR2(10)  NOT NULL,
        estado_anterior       VARCHAR2(20),
        estado_nuevo          VARCHAR2(20),
        estado_pago_anterior  VARCHAR2(20),
        estado_pago_nuevo     VARCHAR2(20),
        cliente_id            NUMBER,
        anulado_por           VARCHAR2(100),
        motivo                VARCHAR2(300),
        fecha_evento          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
        usuario_oracle        VARCHAR2(128) DEFAULT USER NOT NULL,
        programa              VARCHAR2(64),
        usuario_so            VARCHAR2(128),
        CONSTRAINT pk_venta_auditoria PRIMARY KEY (id_auditoria),
        CONSTRAINT ck_venta_auditoria_accion CHECK (accion IN (''INSERT'', ''UPDATE'', ''DELETE'')))
      TABLESPACE ts_sgejd_ventas
      PARTITION BY RANGE (fecha_evento) INTERVAL (NUMTOYMINTERVAL(1, ''MONTH''))
      (PARTITION p_inicio VALUES LESS THAN (TIMESTAMP ''2026-11-01 00:00:00''))');
    ejecutar('CREATE INDEX ix_venta_auditoria_venta ON venta_auditoria (id_venta, fecha_evento) LOCAL');
    ejecutar('CREATE INDEX ix_venta_auditoria_accion ON venta_auditoria (accion) LOCAL');
END;
/

CREATE OR REPLACE TRIGGER trg_venta_estado_bu
BEFORE UPDATE OF estado ON ventas
FOR EACH ROW
BEGIN
    IF :OLD.estado = 'ANULADA' AND :NEW.estado <> 'ANULADA' THEN
        RAISE_APPLICATION_ERROR(-20021,
            'La venta ' || :OLD.id || ' está ANULADA y no puede volver a ' || :NEW.estado || '.');
    END IF;
    IF :OLD.estado = 'REGISTRADA' AND :NEW.estado = 'ANULADA' THEN
        IF LENGTH(TRIM(:NEW.motivo_anulacion)) IS NULL OR LENGTH(TRIM(:NEW.motivo_anulacion)) < 5 THEN
            RAISE_APPLICATION_ERROR(-20022,
                'Para anular la venta ' || :OLD.id || ' indique el motivo (al menos 5 caracteres).');
        END IF;
        IF :NEW.anulado_por IS NULL THEN
            RAISE_APPLICATION_ERROR(-20023, 'Para anular la venta ' || :OLD.id || ' indique quién la anula.');
        END IF;
        :NEW.fecha_anulacion := NVL(:NEW.fecha_anulacion, TRUNC(SYSDATE));
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_venta_auditoria
AFTER INSERT OR UPDATE OR DELETE ON ventas
FOR EACH ROW
DECLARE
    v_accion venta_auditoria.accion%TYPE;
BEGIN
    IF INSERTING THEN
        v_accion := 'INSERT';
    ELSIF UPDATING THEN
        v_accion := 'UPDATE';
    ELSE
        v_accion := 'DELETE';
    END IF;

    INSERT INTO venta_auditoria (id_venta, accion, estado_anterior, estado_nuevo,
                                 estado_pago_anterior, estado_pago_nuevo, cliente_id,
                                 anulado_por, motivo, programa, usuario_so)
    VALUES (COALESCE(:NEW.id, :OLD.id), v_accion, :OLD.estado, :NEW.estado,
            :OLD.estado_pago, :NEW.estado_pago, COALESCE(:NEW.cliente_id, :OLD.cliente_id),
            COALESCE(:NEW.anulado_por, :OLD.anulado_por), COALESCE(:NEW.motivo_anulacion, :OLD.motivo_anulacion),
            SUBSTR(SYS_CONTEXT('USERENV', 'MODULE'), 1, 64), SYS_CONTEXT('USERENV', 'OS_USER'));
END;
/
