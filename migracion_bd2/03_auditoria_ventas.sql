SELECT object_name, object_type, status FROM dba_objects
WHERE owner = 'JDREFRIGERACION' AND object_name IN ('VENTA_AUDITORIA', 'TRG_VENTA_ESTADO_BU', 'TRG_VENTA_AUDITORIA')
  AND object_type <> 'TABLE PARTITION' ORDER BY object_name;
SELECT partitioning_type, interval FROM dba_part_tables WHERE owner = 'JDREFRIGERACION' AND table_name = 'VENTA_AUDITORIA';
