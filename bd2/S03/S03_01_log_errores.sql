set echo on feedback on linesize 200 pagesize 100
whenever sqlerror continue

-- Sin FOREIGN KEY: un error se registra aunque la operación que falló no haya escrito nada
CREATE TABLE log_errores (
    id_log          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objeto          VARCHAR2(60)   NOT NULL,      -- procedimiento o función donde ocurrió
    codigo_error    NUMBER         NOT NULL,      -- SQLCODE: 100 (NO_DATA_FOUND), -1, -20xxx…
    mensaje_error   VARCHAR2(500),
    contexto        VARCHAR2(500),                -- parámetros con los que se llamó
    traza           VARCHAR2(1000),               -- DBMS_UTILITY.FORMAT_ERROR_BACKTRACE: en qué línea
    fecha_evento    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_oracle  VARCHAR2(128)  DEFAULT USER NOT NULL,
    programa        VARCHAR2(64)
);
CREATE INDEX ix_log_errores_fecha ON log_errores (fecha_evento);

-- Registra un error en su PROPIA transacción (ver hallazgo en S03_02): el COMMIT de aquí solo confirma
-- esta fila; no confirma ni deshace nada de la transacción de quien llama.
CREATE OR REPLACE PROCEDURE sp_registrar_error(
    p_objeto   IN VARCHAR2,
    p_codigo   IN NUMBER,
    p_mensaje  IN VARCHAR2,
    p_contexto IN VARCHAR2 DEFAULT NULL
) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO log_errores (objeto, codigo_error, mensaje_error, contexto, traza, programa)
    VALUES (SUBSTR(p_objeto, 1, 60), p_codigo, SUBSTR(p_mensaje, 1, 500), SUBSTR(p_contexto, 1, 500),
            SUBSTR(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE, 1, 1000),
            SUBSTR(SYS_CONTEXT('USERENV', 'MODULE'), 1, 64));
    COMMIT;
END sp_registrar_error;
/
SHOW ERRORS
exit
