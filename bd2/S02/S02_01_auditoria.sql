-- ============================================================
-- BD2 · S2 · Triggers DML y auditoría · SGE-JD
-- Paso 1: tabla de auditoría de la venta. Se ejecuta como JDREFRIGERACION:
--   .\bd2\herramientas\sql.ps1 bd2\S02\S02_01_auditoria.sql
--
-- Sin FOREIGN KEY hacia VENTAS: el registro de un DELETE tiene que sobrevivir a la venta borrada.
-- Además del usuario Oracle guarda el programa y el usuario del sistema operativo: el backend se conecta
-- siempre como JDREFRIGERACION, así que USER solo no dice quién hizo el cambio (hallazgo de S2).
-- ============================================================
set echo on feedback on linesize 200 pagesize 100
whenever sqlerror continue

CREATE TABLE venta_auditoria (
    id_auditoria          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta              NUMBER        NOT NULL,       -- sin FK a propósito
    accion                VARCHAR2(10)  NOT NULL,
    estado_anterior       VARCHAR2(20),
    estado_nuevo          VARCHAR2(20),
    estado_pago_anterior  VARCHAR2(20),
    estado_pago_nuevo     VARCHAR2(20),
    cliente_id            NUMBER,
    anulado_por           VARCHAR2(100),                 -- usuario de Keycloak que guardó el backend
    motivo                VARCHAR2(300),
    fecha_evento          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_oracle        VARCHAR2(128) DEFAULT USER NOT NULL,
    programa              VARCHAR2(64),                  -- sqlplus, JDBC Thin Client, SQL Developer…
    usuario_so            VARCHAR2(128),
    CONSTRAINT ck_venta_auditoria_accion CHECK (accion IN ('INSERT', 'UPDATE', 'DELETE'))
);

CREATE INDEX ix_venta_auditoria_venta ON venta_auditoria (id_venta, fecha_evento);

DESC venta_auditoria
exit
