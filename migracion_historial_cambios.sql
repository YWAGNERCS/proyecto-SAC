-- ============================================================
-- Migración: historial de cambios (seguridad) (30/10/2026)
-- Cada POST/PUT/PATCH/DELETE al panel queda registrado por AuditoriaFilter: quién, cuándo,
-- desde qué IP, qué hizo ("Anuló la venta #113") y cómo terminó (EXITO, DENEGADO, RECHAZADO, ERROR).
-- Solo se agregan filas: la aplicación nunca edita ni borra el historial.
-- Los inicios de sesión no van aquí: los guarda Keycloak (eventos del realm, 7 días).
--
-- Ejecutar UNA vez, con el backend detenido:
--   Get-Content migracion_historial_cambios.sql | docker exec -i SGE-JD sqlplus -s jdrefrigeracion/<password>@FREEPDB1
-- Se puede ejecutar varias veces: si la tabla ya existe, no hace nada.
-- ============================================================
SET FEEDBACK ON

CREATE TABLE IF NOT EXISTS historial_cambios (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora   TIMESTAMP      NOT NULL,
    usuario      VARCHAR2(100)  NOT NULL,
    roles        VARCHAR2(300),
    metodo       VARCHAR2(10)   NOT NULL,
    ruta         VARCHAR2(300)  NOT NULL,
    estado_http  NUMBER(3)      NOT NULL,
    resultado    VARCHAR2(10)   NOT NULL,
    modulo       VARCHAR2(40)   NOT NULL,
    accion       VARCHAR2(300)  NOT NULL,
    detalle      VARCHAR2(500),
    ip           VARCHAR2(64),
    CONSTRAINT ck_historial_resultado CHECK (resultado IN ('EXITO', 'DENEGADO', 'RECHAZADO', 'ERROR'))
);

CREATE INDEX IF NOT EXISTS ix_historial_fecha ON historial_cambios (fecha_hora);
CREATE INDEX IF NOT EXISTS ix_historial_usuario ON historial_cambios (usuario, fecha_hora);

EXIT
