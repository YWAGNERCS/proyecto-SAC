-- Ejecutar con JDREFRIGERACION como esquema actual, después de la migración BD2.
-- Se puede repetir. Las ventas anteriores conservan su enlace actual desde la orden.
DECLARE
    objetos NUMBER;
    esquema VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
BEGIN
    SELECT COUNT(*) INTO objetos FROM ALL_TABLES
    WHERE OWNER = esquema AND TABLE_NAME = 'RESERVAS_AGENDA';
    IF objetos = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE RESERVAS_AGENDA (
            CLAVE VARCHAR2(120 CHAR) NOT NULL,
            CONSTRAINT PK_RESERVAS_AGENDA PRIMARY KEY (CLAVE)
        )';
    END IF;

    SELECT COUNT(*) INTO objetos FROM ALL_TAB_COLUMNS
    WHERE OWNER = esquema AND TABLE_NAME = 'VENTAS' AND COLUMN_NAME = 'ORDEN_TRABAJO_ORIGEN_ID';
    IF objetos = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE VENTAS ADD (ORDEN_TRABAJO_ORIGEN_ID NUMBER(19,0))';
    END IF;

    SELECT COUNT(*) INTO objetos FROM ALL_INDEXES
    WHERE OWNER = esquema AND INDEX_NAME = 'IX_VENTAS_ORDEN_ORIGEN';
    IF objetos = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_VENTAS_ORDEN_ORIGEN ON VENTAS (ORDEN_TRABAJO_ORIGEN_ID)';
    END IF;
END;
/
GRANT SELECT, INSERT, UPDATE ON RESERVAS_AGENDA TO ROL_SGEJD_OPERACION;
