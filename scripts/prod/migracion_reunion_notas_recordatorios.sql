-- Ejecutar como JDREFRIGERACION antes de iniciar la nueva version.
-- Aditiva y repetible: no modifica ventas, cobros, notas ni visitas existentes.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
DECLARE n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM all_tab_columns WHERE owner=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
    AND table_name='NOTAS_CREDITO' AND column_name='AMBIENTE_EMISION';
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE NOTAS_CREDITO ADD (AMBIENTE_EMISION VARCHAR2(13))'; END IF;
  SELECT COUNT(*) INTO n FROM all_tables WHERE owner=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND table_name='RECORDATORIOS_SERVICIO';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE RECORDATORIOS_SERVICIO (
      ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      ORDEN_ID NUMBER NOT NULL,
      ACTIVO NUMBER(1) DEFAULT 0 NOT NULL,
      FRECUENCIA_MESES NUMBER(10) DEFAULT 3 NOT NULL,
      ANTICIPACION_DIAS NUMBER(10) DEFAULT 3 NOT NULL,
      FECHA_SIGUIENTE DATE, FECHA_AVISO DATE,
      CORREO_CLIENTE VARCHAR2(150), CORREO_OFICINA VARCHAR2(150),
      ESTADO_CLIENTE VARCHAR2(12) DEFAULT ''PENDIENTE'', ESTADO_OFICINA VARCHAR2(12) DEFAULT ''PENDIENTE'',
      INTENTOS_CLIENTE NUMBER(10) DEFAULT 0 NOT NULL, INTENTOS_OFICINA NUMBER(10) DEFAULT 0 NOT NULL,
      INTENTO_CLIENTE TIMESTAMP, INTENTO_OFICINA TIMESTAMP,
      ERROR_CLIENTE VARCHAR2(500), ERROR_OFICINA VARCHAR2(500),
      CONSTRAINT UK_RECORDATORIO_ORDEN UNIQUE (ORDEN_ID),
      CONSTRAINT FK_RECORDATORIO_ORDEN FOREIGN KEY (ORDEN_ID) REFERENCES ORDENES_TRABAJO(ID),
      CONSTRAINT CK_RECORDATORIO_FRECUENCIA CHECK (FRECUENCIA_MESES BETWEEN 1 AND 120),
      CONSTRAINT CK_RECORDATORIO_ANTICIPACION CHECK (ANTICIPACION_DIAS BETWEEN 0 AND 30),
      CONSTRAINT CK_RECORDATORIO_ACTIVO CHECK (ACTIVO IN (0,1)),
      CONSTRAINT CK_RECORDATORIO_CLIENTE CHECK (ESTADO_CLIENTE IN (''PENDIENTE'',''ENVIANDO'',''ENVIADO'',''FALLIDO'',''INCIERTO'')),
      CONSTRAINT CK_RECORDATORIO_OFICINA CHECK (ESTADO_OFICINA IN (''PENDIENTE'',''ENVIANDO'',''ENVIADO'',''FALLIDO'',''INCIERTO''))
    )';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_RECORDATORIO_AVISO ON RECORDATORIOS_SERVICIO(ACTIVO,FECHA_AVISO)';
  END IF;
END;
/
CREATE OR REPLACE TRIGGER TRG_NOTA_AMBIENTE
BEFORE UPDATE OF AMBIENTE_EMISION ON NOTAS_CREDITO FOR EACH ROW
BEGIN
  IF :OLD.AMBIENTE_EMISION IS NOT NULL AND (:NEW.AMBIENTE_EMISION IS NULL OR :NEW.AMBIENTE_EMISION<>:OLD.AMBIENTE_EMISION) THEN
    RAISE_APPLICATION_ERROR(-20032,'El ambiente de emision de una nota no se puede cambiar.');
  END IF;
END;
/
DECLARE n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM all_users WHERE username='JD_APP';
  IF n>0 THEN EXECUTE IMMEDIATE 'GRANT SELECT,INSERT,UPDATE ON RECORDATORIOS_SERVICIO TO JD_APP'; END IF;
  FOR r IN (SELECT role FROM session_roles WHERE role IN ('ROL_SGEJD_OPERACION','ROL_SGEJD_CONSULTA')) LOOP
    IF r.role='ROL_SGEJD_OPERACION' THEN EXECUTE IMMEDIATE 'GRANT SELECT,INSERT,UPDATE ON RECORDATORIOS_SERVICIO TO ROL_SGEJD_OPERACION';
    ELSE EXECUTE IMMEDIATE 'GRANT SELECT ON RECORDATORIOS_SERVICIO TO ROL_SGEJD_CONSULTA'; END IF;
  END LOOP;
END;
/
