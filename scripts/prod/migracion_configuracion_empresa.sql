-- Ejecutar con JDREFRIGERACION como esquema actual, después de la migración BD2.
-- Se puede repetir. No inserta datos bancarios ni contactos de ejemplo.
DECLARE
    tablas NUMBER;
BEGIN
    SELECT COUNT(*) INTO tablas FROM ALL_TABLES
    WHERE OWNER = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AND TABLE_NAME = 'CONFIGURACION_EMPRESA';
    IF tablas = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE CONFIGURACION_EMPRESA (
            ID NUMBER(19,0) NOT NULL,
            WHATSAPP VARCHAR2(30 CHAR),
            CUENTA_BCP VARCHAR2(50 CHAR),
            CCI_BCP VARCHAR2(50 CHAR),
            CUENTA_NACION VARCHAR2(50 CHAR),
            ACTUALIZADO_POR VARCHAR2(100 CHAR),
            FECHA_ACTUALIZACION TIMESTAMP(6),
            CONSTRAINT PK_CONFIGURACION_EMPRESA PRIMARY KEY (ID),
            CONSTRAINT CK_CONFIG_EMPRESA_UNICA CHECK (ID = 1)
        )';
    END IF;
END;
/
GRANT SELECT, INSERT, UPDATE ON CONFIGURACION_EMPRESA TO ROL_SGEJD_OPERACION;
